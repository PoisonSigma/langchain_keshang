模式的作用
通常情况下，模式可以匹配值，解构值，或根据上下文和模式的形状同时进行匹配和解构。

首先，模式匹配允许您检查给定值是否：

具有某种形状。
是某个常量。
等于其他某个值。
具有某种类型。
然后，模式解构为您提供了一种方便的声明性语法，将该值分解为其组成部分。同一模式还可以允许您在此过程中将变量绑定到其中的某些或所有部分。

匹配
模式始终针对值进行测试，以确定该值是否具有您期望的形式。换句话说，您正在检查值是否与模式匹配。

构成匹配取决于您使用的模式类型。例如，常量模式匹配如果值等于模式的常量：

switch (number) {
// 如果1 == number，则常量模式匹配。
case 1:
print('one');
}
许多模式使用子模式，有时分别称为外部模式和内部模式。模式在其子模式上递归匹配。例如，任何集合类型模式的各个字段都可以是变量模式或常量模式：

const a = 'a';
const b = 'b';
switch (obj) {
// List模式[a，b]首先匹配obj，如果obj是具有两个字段的列表，
// 然后如果其字段与常量子模式'a'和'b'匹配。
case [a, b]:
print('$a, $b');
}
要忽略匹配值的某些部分，可以使用通配符模式作为占位符。在列表模式的情况下，可以使用剩余元素。

解构
当对象和模式匹配时，模式可以访问对象的数据并将其分解成部分。换句话说，模式将对象解构为：

