var [a, b, c] = numList;
// ...并将它们分配给新变量。
print(a + b + c);
您可以在解构模式中嵌套任何类型的模式。例如，此case模式匹配和解构一个两个元素的列表，其第一个元素是'a'或'b'：

switch (list) {
case ['a' || 'b', var c]:
print(c);
}
